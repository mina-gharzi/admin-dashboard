/*
  ==========================================================
  utils/filters.ts
  ----------------------------------------------------------
  فیلترهای صفحات لیست (سفارش‌ها/محصولات/مشتریان) همیشه یه
  گزینه‌ی «همه» + مقادیر واقعی enum اون entity رو دارن. قبلاً
  این state ها با `useState("همه")` تعریف می‌شدن که TypeScript
  نوعشون رو `string` خام inference می‌کرد — یعنی هیچ ارتباطی
  به union واقعی وضعیت/دسته‌بندی نداشت و یه typo تو مقدار
  فیلتر هیچ خطایی نمی‌داد.

  `StatusFilter<T>` دقیقاً همون شکل رو (مقادیر واقعی + «همه»)
  type-safe می‌کنه.
  ==========================================================
*/

export type StatusFilter<T extends string> = T | "همه";
